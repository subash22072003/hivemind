/**
 * One-time setup: creates poster + 3 worker sub-accounts under your master
 * testnet account and gives each worker a FUNCTION-CALL ACCESS KEY limited to
 * `place_bid` and `submit_result` on the market contract.
 *
 * That is the security story: an agent can bid and deliver work, but its key
 * cannot transfer funds, cannot call any other contract, and its allowance
 * caps total spend. Escrowed money is untouchable by agents.
 *
 *   npm run setup:keys
 *
 * Requires MASTER_ACCOUNT_ID / MASTER_PRIVATE_KEY and CONTRACT_ID in .env.
 * Prints ready-to-paste .env lines for the poster and workers.
 */
const nearAPI = require('near-api-js');
const { KeyPair, utils } = nearAPI;
const { connectAccount } = require('./market-near');
const { cfg, PERSONALITIES } = require('./config');

const POSTER_BALANCE = '2.5'; // NEAR — poster funds the bounties it locks in escrow
const WORKER_BALANCE = '0.4'; // NEAR — workers only pay gas (fractions of a cent per call)
const KEY_ALLOWANCE = '0.3'; // NEAR — max a worker's function-call key can ever spend

async function main() {
  if (!cfg.master.accountId) throw new Error('Set MASTER_ACCOUNT_ID / MASTER_PRIVATE_KEY in .env');
  if (!cfg.contractId) throw new Error('Set CONTRACT_ID in .env first');

  const master = await connectAccount(cfg, cfg.master.accountId, cfg.master.privateKey);
  const envLines = [];

  const targets = [
    { label: 'POSTER', name: 'poster', methods: null }, // full-access key: hires, approves, rates
    ...PERSONALITIES.map((p, i) => ({
      label: `WORKER${i + 1}`,
      name: p.name.toLowerCase(),
      methods: ['place_bid', 'submit_result'], // sandboxed agent key
    })),
  ];

  for (const t of targets) {
    const accountId = `${t.name}.${cfg.master.accountId}`;
    const keyPair = KeyPair.fromRandom('ed25519');
    const publicKey = keyPair.getPublicKey().toString();

    const balance = t.methods ? WORKER_BALANCE : POSTER_BALANCE;
    try {
      await master.createAccount(
        accountId,
        keyPair.getPublicKey().toString(),
        utils.format.parseNearAmount(balance)
      );
      console.log(`✓ created ${accountId} (${balance} NEAR)`);
    } catch (e) {
      console.log(`• ${accountId} may already exist (${e.message.split('\n')[0]}) — adding key only`);
    }

    if (t.methods) {
      try {
        await master.addKey(
          publicKey,
          cfg.contractId,
          t.methods,
          utils.format.parseNearAmount(KEY_ALLOWANCE)
        );
        console.log(
          `  🔑 function-call key: only [${t.methods.join(', ')}] on ${cfg.contractId}, allowance ${KEY_ALLOWANCE} NEAR`
        );
      } catch (e) {
        console.log(`  ⚠️  addKey failed: ${e.message.split('\n')[0]}`);
      }
    }

    envLines.push(`${t.label}_ACCOUNT_ID=${accountId}`);
    envLines.push(`${t.label}_PRIVATE_KEY=${keyPair.toString()}`);
  }

  // Append fresh credentials to .env (old WORKER/POSTER lines are superseded
  // by the latest block at the bottom).
  const fs = require('fs');
  const path = require('path');
  const envPath = path.join(__dirname, '..', '.env');
  fs.appendFileSync(envPath, '\n# ---- generated by setup:keys ----\n' + envLines.join('\n') + '\n');
  console.log('\n✓ credentials appended to agents/.env\n');
}

main().catch((e) => {
  console.error(`✖ ${e.message}`);
  process.exit(1);
});
